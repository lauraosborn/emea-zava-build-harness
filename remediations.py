def inject_xaml_watermark(root: Path):
    """
    Inject the Zava branding + 'Built by Surface AI Factory' watermark and the
    NPU/AI-transparency status bar into the main window XAML.

    Returns (status, detail):
      ("applied", path)      — watermark written into the main UI
      ("present", path)      — already compliant
      ("no-ui", None)        — no XAML surface exists (caller must escalate)
      ("no-anchor", path)    — XAML found but no safe insertion point (escalate)
    """
    xaml_files = [f for f in root.rglob("*.xaml")
                  if not any(p in f.parts for p in (".git", "bin", "obj"))
                  and not f.name.endswith(".g.xaml")]
    if not xaml_files:
        return "no-ui", None

    main_xaml = None
    for candidate_name in ("MainWindow.xaml", "MainPage.xaml", "Shell.xaml"):
        matches = [f for f in xaml_files if f.name == candidate_name]
        if matches:
            main_xaml = matches[0]
            break
    if not main_xaml:
        # Never treat App.xaml as the main UI — it has no visual tree.
        visual = [f for f in xaml_files if f.name != "App.xaml"]
        if not visual:
            return "no-ui", None
        main_xaml = visual[0]

    content = _read(main_xaml)
    has_watermark = re.search(r"built\s+by\s+surface\s+ai\s+factory", content, re.IGNORECASE)
    has_zava = re.search(r"\bzava\b", content, re.IGNORECASE)
    if has_watermark and has_zava:
        return "present", str(main_xaml)

    branding_xaml = (
        '\n    <!-- Surface AI Factory branding (Section 1.1) — do not remove -->\n'
        '    <StackPanel x:Name="ZavaBrandingBar" Orientation="Horizontal" Spacing="8"\n'
        '                HorizontalAlignment="Left" VerticalAlignment="Top" Margin="12,8,0,0">\n'
        '        <Image Source="ms-appx:///Assets/zava-logo.png" Height="20"\n'
        '               AutomationProperties.Name="Zava logo" />\n'
        '        <TextBlock Text="Zava" FontWeight="SemiBold" VerticalAlignment="Center" />\n'
        '    </StackPanel>\n'
        f'    <TextBlock x:Name="WatermarkText" Text="{WATERMARK_TEXT}"\n'
        '               FontSize="10" Opacity="0.6"\n'
        '               HorizontalAlignment="Right" VerticalAlignment="Bottom"\n'
        '               Margin="0,0,8,4" />\n'
    )
    npu_bar_xaml = (
        '\n    <!-- Surface AI Factory AI transparency (Section 1.2) -->\n'
        '    <StackPanel x:Name="NpuStatusBar" Orientation="Horizontal"\n'
        '                HorizontalAlignment="Right" VerticalAlignment="Top" Margin="0,8,8,0">\n'
        '        <TextBlock x:Name="ModelNameText"  Text="Model: Loading..."   FontSize="11" Margin="0,0,16,0"/>\n'
        '        <TextBlock x:Name="LocalAiText"    Text="Local AI: On-device" FontSize="11" Margin="0,0,16,0"/>\n'
        '        <TextBlock x:Name="NpuStatusText"  Text="NPU: Detecting..."   FontSize="11" Margin="0,0,16,0"/>\n'
        '        <TextBlock x:Name="TokenSpeedText" Text="Tokens: 0 tok/s"     FontSize="11"/>\n'
        '    </StackPanel>\n'
    )
    payload = branding_xaml + npu_bar_xaml

    # Insert before the final closing container tag. Verify the substitution
    # actually happened — the previous implementation wrote the file even when
    # the pattern did not match, silently reporting success.
    new_content, n = re.subn(
        r"(</Grid>|</StackPanel>|</Page>|</Window>|</UserControl>)(\s*)$",
        payload + r"\1\2",
        content,
        count=1,
        flags=re.IGNORECASE,
    )
    if n == 0:
        return "no-anchor", str(main_xaml)

    _write(main_xaml, new_content)
    return "applied", str(main_xaml)


