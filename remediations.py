def remediate_readme(root: Path, repo_name: str = "this-repo", model_name: str = "phi-3.5-mini-instruct-onnx"):
    """Ensure README has all required sections."""
    readme_path, content = _get_or_create_readme(root)
    modified = False

    # Attribution at top — must carry BOTH the watermark and Zava branding.
    has_watermark = re.search(r"built\s+by\s+surface\s+ai\s+factory", content, re.IGNORECASE)
    has_zava = re.search(r"\bzava\b", content, re.IGNORECASE)
    if not (has_watermark and has_zava):
        if has_watermark and not has_zava:
            # Watermark present but Zava missing — prepend company branding only.
            content = (
                '<img src="Assets/zava-logo.png" alt="Zava" height="32" />\n\n'
                "# Zava\n\n"
            ) + content
        elif not has_watermark:
            content = README_ATTRIBUTION + content
        modified = True

    # Surface differentiators
    if not re.search(r"surface differentiator|npu acceleration.*battery|copilot\+.*pc.*feature", content, re.IGNORECASE):
        content += SURFACE_DIFFERENTIATORS_SECTION
        modified = True

    # Setup section
    if not re.search(r"##.*setup|##.*install|##.*getting.started", content, re.IGNORECASE):
        sol_files = list(root.rglob("*.sln"))
        solution_file = sol_files[0].name if sol_files else "Solution.sln"
        content += SETUP_SECTION.format(
            repo_name=repo_name,
            model_name=model_name,
            solution_file=solution_file
        )
        modified = True

    # Architecture
    if not re.search(r"##.*architecture|##.*design", content, re.IGNORECASE):
        content += ARCHITECTURE_SECTION
        modified = True
    elif not (
        re.search(r"local\s+ai|on-?device|foundry\s+local|onnx|npu", content, re.IGNORECASE)
        and re.search(r"```mermaid|flowchart|graph\s+(TD|LR)|architecture\s+flow|local\s+ai\s+.*flow", content, re.IGNORECASE)
    ):
        content += LOCAL_AI_ARCHITECTURE_FLOW_SECTION
        modified = True

    # Model requirements
    if not re.search(r"##.*model.*req|##.*require.*model", content, re.IGNORECASE):
        content += MODEL_REQUIREMENTS_SECTION
        modified = True

    # GPU fallback policy
    if not re.search(r"##.*gpu.*fallback|gpufallbackconsent", content, re.IGNORECASE):
        content += GPU_FALLBACK_SECTION
        modified = True

    # Demo script
    if not re.search(r"##.*demo.*script|##.*script.*demo", content, re.IGNORECASE):
        content += DEMO_SCRIPT_SECTION
        modified = True

    # Troubleshooting
    if not re.search(r"##.*troubleshoot", content, re.IGNORECASE):
        content += TROUBLESHOOTING_SECTION
        modified = True

    # Disclaimer
    if not re.search(r"##.*disclaimer|educational.*demo|prototype.*purpose", content, re.IGNORECASE):
        content += DISCLAIMER_SECTION
        modified = True

    if modified:
        _write(readme_path, content)
        return True
    return False


