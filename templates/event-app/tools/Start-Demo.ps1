<#
.SYNOPSIS
    Build (if needed) and launch __APP_TITLE__ for a live session.
.DESCRIPTION
    Generated by Zava Live Build. Run the harness preflight first:
        python harness.py --preflight <this folder>
    so the NPU model is compiled and the replay safety net is recorded.
#>
param(
    [switch]$Rebuild,
    [switch]$Warmup
)
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$project = Join-Path $root 'src\__APP__\__APP__.csproj'
$platform = if ($env:PROCESSOR_ARCHITECTURE -eq 'ARM64') { 'ARM64' } else { 'x64' }

function Find-Exe {
    Get-ChildItem (Join-Path $root "src\__APP__\bin\$platform\Release") -Filter '__APP__.exe' -Recurse -ErrorAction SilentlyContinue |
        Sort-Object LastWriteTime -Descending | Select-Object -First 1
}

$exe = Find-Exe
if ($Rebuild -or -not $exe) {
    Write-Host "Building __APP__ (Release|$platform)..." -ForegroundColor Cyan
    dotnet build $project -c Release -p:Platform=$platform --nologo -v minimal
    if ($LASTEXITCODE -ne 0) { throw 'Build failed.' }
    $exe = Find-Exe
}

if ($Warmup) {
    Write-Host 'Warming up: compiling the model for the NPU and recording replay outputs...' -ForegroundColor Cyan
    $p = Start-Process $exe.FullName -ArgumentList '--warmup' -PassThru -Wait
    Get-Content (Join-Path $env:LOCALAPPDATA '__APP__\warmup.json')
    exit $p.ExitCode
}

Write-Host "Launching $($exe.FullName)" -ForegroundColor Green
Start-Process $exe.FullName
