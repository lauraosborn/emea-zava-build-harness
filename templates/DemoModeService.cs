using System;
using System.Collections.Generic;
using System.Threading;
using System.Threading.Tasks;

namespace NAMESPACE.Services
{
    /// <summary>
    /// Demo Mode service — provides mock inference when NPU or model is unavailable.
    /// Best Practice §9: Resilience & Reliability.
    /// Inference hierarchy: NPU → (user-consented) GPU fallback for large models → Mock Inference → Error Message.
    /// See <see cref="InferenceHardwareSelector"/> for the full orchestration and
    /// <see cref="IGpuFallbackConsentService"/> for the mandatory consent gate before any GPU use.
    /// </summary>
    public class DemoModeService : IInferenceService
    {
        public string ModelName => "Mock Model (Demo Mode)";
        public bool IsReady => true;
        public bool IsNpuActive => false;
        public bool IsGpuActive => false;
        public HardwareTier ActiveTier => HardwareTier.MockDemo;

        private static readonly string[] MockResponses =
        [
            "This is a demo response. In production, this would be generated by the on-device AI model running on the NPU.",
            "Surface AI Factory demo mode is active. All responses are pre-scripted for demonstration reliability.",
            "NPU-accelerated inference delivers up to 4× better efficiency than CPU inference on Copilot+ PCs.",
            "This prototype runs entirely offline. No data leaves your device — full privacy by design."
        ];

        private int _responseIndex = 0;

        public Task<string> CompleteAsync(
            string prompt,
            InferenceOptions? options = null,
            CancellationToken cancellationToken = default)
        {
            var response = MockResponses[_responseIndex % MockResponses.Length];
            _responseIndex++;
            return Task.FromResult(response);
        }

        public async IAsyncEnumerable<string> StreamAsync(
            string prompt,
            InferenceOptions? options = null,
            [System.Runtime.CompilerServices.EnumeratorCancellation] CancellationToken cancellationToken = default)
        {
            var response = await CompleteAsync(prompt, options, cancellationToken);
            var words = response.Split(' ');
            foreach (var word in words)
            {
                yield return word + " ";
                await Task.Delay(50, cancellationToken); // simulate streaming
            }
        }

        public Task LoadModelAsync(string modelId, CancellationToken cancellationToken = default)
            => Task.CompletedTask; // Nothing to load in demo mode

        /// <summary>
        /// Legacy simple selector: returns the real inference service if NPU is available,
        /// otherwise Demo Mode. This does NOT include GPU fallback — prefer
        /// <see cref="InferenceHardwareSelector"/> for the full NPU → consent-gated-GPU →
        /// Mock hierarchy required by Best Practice §3/§9.
        /// </summary>
        public static IInferenceService SelectService(
            IInferenceService? realService,
            NpuTelemetryService telemetry,
            bool forceDemoMode = false)
        {
            if (forceDemoMode || !telemetry.NpuDetected || !telemetry.NpuAccessible)
            {
                Console.WriteLine("[DemoMode] NPU unavailable — switching to mock inference.");
                return new DemoModeService();
            }
            return realService ?? new DemoModeService();
        }
    }
}
